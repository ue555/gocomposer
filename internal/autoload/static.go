// exportArr models the arrays var_export()ed into autoload_static.php.
type exportArr struct {
	keys []string
	vals map[string]any // string, int, *exportArr
}

func newExportArr() *exportArr { return &exportArr{vals: map[string]any{}} }

func (a *exportArr) set(k string, v any) {
	if _, ok := a.vals[k]; !ok {
		a.keys = append(a.keys, k)
	}
	a.vals[k] = v
}

func (a *exportArr) sub(k string) *exportArr {
	if v, ok := a.vals[k].(*exportArr); ok {
		return v
	}
	s := newExportArr()
	a.set(k, s)
	return s
}

func listArr(items []string) *exportArr {
	a := newExportArr()
	for i, s := range items {
		a.set(strconv.Itoa(i), s)
	}
	return a
}

// varExport mirrors php_var_export_ex for arrays of strings/ints.
func varExport(v any, level int, sb *strings.Builder) {
	switch t := v.(type) {
	case *exportArr:
		if level > 1 {
			sb.WriteByte('\n')
			sb.WriteString(strings.Repeat(" ", level-1))
		}
		sb.WriteString("array (\n")
		for _, k := range t.keys {
			sb.WriteString(strings.Repeat(" ", level+1))
			if _, isInt := phpjson.IntKey(k); isInt {
				sb.WriteString(k)
			} else {
				sb.WriteString(fsutil.VarExport(k))
			}
			sb.WriteString(" => ")
			varExport(t.vals[k], level+2, sb)
			sb.WriteString(",\n")
		}
		if level > 1 {
			sb.WriteString(strings.Repeat(" ", level-1))
		}
		sb.WriteByte(')')
	case string:
		sb.WriteString(fsutil.VarExport(t))
	case int:
		sb.WriteString(strconv.Itoa(t))
	}
}

// strtr is PHP strtr($s, array) (longest keys first at each position).
func strtr(s string, repl map[string]string) string {
	var keys []string
	for k := range repl {
		if k != "" {
			keys = append(keys, k)
		}
	}
	sort.Slice(keys, func(i, j int) bool { return len(keys[i]) > len(keys[j]) })
	var sb strings.Builder
	for i := 0; i < len(s); {
		matched := false
		for _, k := range keys {
			if strings.HasPrefix(s[i:], k) {
				sb.WriteString(repl[k])
				i += len(k)
				matched = true
				break
			}
		}
		if !matched {
			sb.WriteByte(s[i])
			i++
		}
	}
	return sb.String()
}

var (
	reLeadingSpaces  = regexp.MustCompile(`(?m)^ *`)
	reTrailingSpaces = regexp.MustCompile(`(?m) +$`)
)

func (g *gen) staticFile(suffix, realTarget string, hasFiles bool, filesAbs map[string]string, autoloads *autoloadData, psr0Abs, psr4Abs map[string][]string, classes []string, classAbs map[string]string) string {
	file := "<?php\n\n// autoload_static.php @generated by Composer\n\nnamespace Composer\\Autoload;\n\nclass ComposerStaticInit" + suffix + "\n{\n"
	vendorCode, _ := fsutil.FindShortestPathCode(realTarget, g.vendorPath, true, true, false)
	baseCode, _ := fsutil.FindShortestPathCode(realTarget, g.basePath, true, true, false)
	vendorPathCode := " => " + vendorCode + " . '/"
	vendorPharPathCode := " => 'phar://' . " + vendorCode + " . '/"
	appBaseDirCode := " => " + baseCode + " . '/"
	appBaseDirPharCode := " => 'phar://' . " + baseCode + " . '/"
	exportPrefix := func(p string) string {
		e := fsutil.VarExport(strings.TrimRight(p, `\/`) + "/")
		return " => " + e[:len(e)-1]
	}
	repl := map[string]string{
		exportPrefix(g.vendorPath):             vendorPathCode,
		exportPrefix("phar://" + g.vendorPath): vendorPharPathCode,
		exportPrefix(g.basePath):               appBaseDirCode,
		exportPrefix("phar://" + g.basePath):   appBaseDirPharCode,
	}
	type prop struct {
		name string
		val  *exportArr
	}
	var props []prop
	if hasFiles {
		fa := newExportArr()
		for _, id := range autoloads.files.keys {
			fa.set(id, filesAbs[id])
		}
		props = append(props, prop{"files", fa})
	}
	prefixLengths := newExportArr()
	prefixDirs := newExportArr()
	var fallbackPsr4 []string
	for _, ns := range autoloads.psr4.keys {
		paths := psr4Abs[ns]
		if ns == "" {
			fallbackPsr4 = paths
			continue
		}
		prefixLengths.sub(ns[:1]).set(ns, len(ns))
		prefixDirs.set(ns, listArr(paths))
	}
	prefixesPsr0 := newExportArr()
	var fallbackPsr0 []string
	for _, ns := range autoloads.psr0.keys {
		paths := psr0Abs[ns]
		if ns == "" {
			fallbackPsr0 = paths
			continue
		}
		prefixesPsr0.sub(ns[:1]).set(ns, listArr(paths))
	}
	classMap := newExportArr()
	for _, c := range classes {
		classMap.set(c, classAbs[c])
	}
	if len(prefixLengths.keys) > 0 {
		props = append(props, prop{"prefixLengthsPsr4", prefixLengths})
	}
	if len(prefixDirs.keys) > 0 {
		props = append(props, prop{"prefixDirsPsr4", prefixDirs})
	}
	if len(fallbackPsr4) > 0 {
		props = append(props, prop{"fallbackDirsPsr4", listArr(fallbackPsr4)})
	}
	if len(prefixesPsr0.keys) > 0 {
		props = append(props, prop{"prefixesPsr0", prefixesPsr0})
	}
	if len(fallbackPsr0) > 0 {
		props = append(props, prop{"fallbackDirsPsr0", listArr(fallbackPsr0)})
	}
	if len(classMap.keys) > 0 {
		props = append(props, prop{"classMap", classMap})
	}
	initializer := ""
	for _, p := range props {
		var sb strings.Builder
		varExport(p.val, 1, &sb)
		value := strtr(sb.String(), repl)
		value = reLeadingSpaces.ReplaceAllStringFunc(value, func(m string) string { return "    " + m + m })
		value = strings.TrimLeft(value, " \t\n\r\x00\x0B")
		value = reTrailingSpaces.ReplaceAllString(value, "")
		file += "    public static $" + p.name + " = " + value + ";\n\n"
		if p.name != "files" {
			initializer += "            $loader->" + p.name + " = ComposerStaticInit" + suffix + "::$" + p.name + ";\n"
		}
	}
	return file + "    public static function getInitializer(ClassLoader $loader)\n    {\n        return \\Closure::bind(function () use ($loader) {\n" + initializer + "\n        }, null, ClassLoader::class);\n    }\n}\n"
}

var reExtTarget = regexp.MustCompile(`(?i)^ext-(.+)$`)

func (g *gen) platformCheck(packageMap []PackageEntry, checkPlatform phpjson.Value, devPackageNames []string, ignored func(string) bool) string {
	lowest := semver.ZeroBound()
	requiredPhp64 := false
	requiredExtensions := map[string]string{}
	var extKeys []string
	extensionProviders := map[string][]semver.Constraint{}
	for _, e := range packageMap {
		for _, l := range append(append(pkg.Links(nil), e.Pkg.Replaces()...), e.Pkg.Provides()...) {
			if m := reExtTarget.FindStringSubmatch(l.Target); m != nil {
				extensionProviders[m[1]] = append(extensionProviders[m[1]], l.Constraint)
			}
		}
	}
	isDev := map[string]bool{}
	for _, n := range devPackageNames {
		isDev[n] = true
	}
	for _, e := range packageMap {
		if isDev[e.Pkg.Name] {
			continue
		}
	links:
		for _, l := range e.Pkg.Requires() {
			if ignored != nil && ignored(l.Target) {
				continue
			}
			if l.Target == "php" || l.Target == "php-64bit" {
				if lb := l.Constraint.LowerBound(); lb.CompareTo(lowest, ">") {
					lowest = lb
				}
			}
			if l.Target == "php-64bit" {
				requiredPhp64 = true
			}
			if checkPlatform == true {
				if m := reExtTarget.FindStringSubmatch(l.Target); m != nil {
					for _, provided := range extensionProviders[m[1]] {
						if provided.Matches(l.Constraint) {
							continue links
						}
					}
					ext := m[1]
					if ext == "zend-opcache" {
						ext = "zend opcache"
					}
					exported := fsutil.VarExport(ext)
					line := "extension_loaded(" + exported + ") || $missingExtensions[] = " + exported + ";\n"
					if ext == "pcntl" || ext == "readline" {
						line = "PHP_SAPI !== 'cli' || extension_loaded(" + exported + ") || $missingExtensions[] = " + exported + ";\n"
					}
					if _, ok := requiredExtensions[exported]; !ok {
						extKeys = append(extKeys, exported)
					}
					requiredExtensions[exported] = line
				}
			}
		}
	}
	sort.SliceStable(extKeys, func(i, j int) bool { return phpjson.PHPCompareKeys(extKeys[i], extKeys[j]) < 0 })
	formatID := func(b semver.Bound) int {
		if b.IsZero() {
			return 0
		}
		if b.IsPositiveInfinity() {
			return 99999
		}
		chunks := strings.Split(strings.ReplaceAll(b.Version, "-", "."), ".")
		n := func(i int) int {
			if i >= len(chunks) {
				return 0
			}
			v, _ := strconv.Atoi(numericPrefix(chunks[i]))
			return v
		}
		return n(0)*10000 + n(1)*100 + n(2)
	}
	formatHuman := func(b semver.Bound) string {
		if b.IsZero() {
			return "0"
		}
		if b.IsPositiveInfinity() {
			return "99999"
		}
		chunks := strings.Split(strings.ReplaceAll(b.Version, "-", "."), ".")
		if len(chunks) > 3 {
			chunks = chunks[:3]
		}
		return strings.Join(chunks, ".")
	}
	requiredPhp := ""
	if !lowest.IsZero() {
		op := ">"
		if lowest.Inclusive {
			op = ">="
		}
		check := "PHP_VERSION_ID " + op + " " + strconv.Itoa(formatID(lowest))
		errStr := `"` + op + " " + formatHuman(lowest) + `"`
		requiredPhp = "\nif (!(" + check + ")) {\n    $issues[] = 'Your Composer dependencies require a PHP version " + errStr + ". You are running ' . PHP_VERSION . '.';\n}\n"
	}
	if requiredPhp64 {
		requiredPhp += "\nif (PHP_INT_SIZE !== 8) {\n    $issues[] = 'Your Composer dependencies require a 64-bit build of PHP.';\n}\n"
	}
	exts := ""
	for _, k := range extKeys {
		exts += requiredExtensions[k]
	}
	if exts != "" {
		exts = "\n$missingExtensions = array();\n" + exts + "\nif ($missingExtensions) {\n    $issues[] = 'Your Composer dependencies require the following PHP extensions to be installed: ' . implode(', ', $missingExtensions) . '.';\n}\n"
	}
	if requiredPhp == "" && exts == "" {
		return ""
	}
	return "<?php\n\n// platform_check.php @generated by Composer\n\n$issues = array();\n" + requiredPhp + exts + `
if ($issues) {
    if (!headers_sent()) {
        header('HTTP/1.1 500 Internal Server Error');
    }
    if (!ini_get('display_errors')) {
        if (PHP_SAPI === 'cli' || PHP_SAPI === 'phpdbg') {
            fwrite(STDERR, 'Composer detected issues in your platform:' . PHP_EOL.PHP_EOL . implode(PHP_EOL, $issues) . PHP_EOL.PHP_EOL);
        } elseif (!headers_sent()) {
            echo 'Composer detected issues in your platform:' . PHP_EOL.PHP_EOL . str_replace('You are running '.PHP_VERSION.'.', '', implode(PHP_EOL, $issues)) . PHP_EOL.PHP_EOL;
        }
    }
    throw new \RuntimeException(
        'Composer detected issues in your platform: ' . implode(' ', $issues)
    );
}
`
}

func numericPrefix(s string) string {
	i := 0
	for i < len(s) && s[i] >= '0' && s[i] <= '9' {
		i++
	}
	if i == 0 {
		return "0"
	}
	return s[:i]
}
