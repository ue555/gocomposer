// Options configure a dump.
type Options struct {
	VendorDir             string
	Cwd                   string
	DevMode               *bool // nil: read installed.json
	ClassMapAuthoritative bool
	Apcu                  bool
	ApcuPrefix            string
	Optimize              bool // scanPsrPackages
	Suffix                string
	ConfigSuffix          string
	LockContentHash       string
	UseIncludePath        bool
	PrependAutoloader     bool
	PlatformCheck         phpjson.Value // false | true | "php-only"
	IgnorePlatform        func(string) bool
	IgnoreAllPlatform     bool
	StrictAmbiguous       bool
	DryRun                bool
	Warn                  func(string)
}

// PackageEntry pairs a package with its install path ("" for root, nil = not installed).
type PackageEntry struct {
	Pkg         *pkg.Package
	InstallPath *string
}

// Result is what dump() returns.
type Result struct {
	ClassMap      *ClassMap
	PsrViolations []string
	DevMode       bool
}

func pathPtr(s string) *string { return &s }

// Dump is AutoloadGenerator::dump.
func Dump(opts Options, root *pkg.Package, packages []*pkg.Package, installPath func(*pkg.Package) string, devPackageNames []string) (*Result, error) {
	scanPsr := opts.Optimize || opts.ClassMapAuthoritative
	devMode := false
	if opts.DevMode != nil {
		devMode = *opts.DevMode
	} else if data, err := os.ReadFile(opts.VendorDir + "/composer/installed.json"); err == nil {
		if v, err := phpjson.Decode(data); err == nil {
			if m := phpjson.AsMap(v); m != nil {
				if d, ok := m.Get("dev"); ok {
					devMode = phpjson.Truthy(d)
				}
			}
		}
	}
	warn := opts.Warn
	if warn == nil {
		warn = func(string) {}
	}
	if err := os.MkdirAll(opts.VendorDir, 0o777); err != nil {
		return nil, err
	}
	basePath := fsutil.NormalizePath(fsutil.Realpath(opts.Cwd))
	vendorPath := fsutil.NormalizePath(fsutil.Realpath(opts.VendorDir))
	targetDir := vendorPath + "/composer"
	if err := os.MkdirAll(targetDir, 0o777); err != nil {
		return nil, err
	}
	realTarget := fsutil.Realpath(targetDir)
	vendorPathCode, _ := fsutil.FindShortestPathCode(realTarget, vendorPath, true, false, false)
	vendorPathToTargetDirCode, _ := fsutil.FindShortestPathCode(vendorPath, realTarget, true, false, false)
	appBaseDirCode, _ := fsutil.FindShortestPathCode(vendorPath, basePath, true, false, false)
	appBaseDirCode = strings.ReplaceAll(appBaseDirCode, "__DIR__", "$vendorDir")

	g := &gen{basePath: basePath, vendorPath: vendorPath, devMode: devMode, root: root, cwd: opts.Cwd}
	packageMap := []PackageEntry{{root, pathPtr("")}}
	for _, p := range packages {
		if p.AliasOf != nil {
			continue
		}
		if err := validatePackage(p); err != nil {
			return nil, err
		}
		var ip *string
		if p.Type() != "metapackage" {
			ip = pathPtr(installPath(p))
		}
		packageMap = append(packageMap, PackageEntry{p, ip})
	}
	var filtered any = false
	if !devMode {
		if len(devPackageNames) > 0 {
			filtered = devPackageNames
		} else {
			filtered = true
		}
	}
	autoloads := g.parseAutoloads(packageMap, filtered)

	namespacesFile := "<?php\n\n// autoload_namespaces.php @generated by Composer\n\n$vendorDir = " + vendorPathCode + ";\n$baseDir = " + appBaseDirCode + ";\n\nreturn array(\n"
	psr4File := "<?php\n\n// autoload_psr4.php @generated by Composer\n\n$vendorDir = " + vendorPathCode + ";\n$baseDir = " + appBaseDirCode + ";\n\nreturn array(\n"
	type pathEntry struct {
		code string
		abs  string
	}
	psr0Abs := map[string][]string{}
	for _, ns := range autoloads.psr0.keys {
		var codes []string
		for _, p := range autoloads.psr0.vals[ns] {
			code, abs := g.getPathCode(p)
			codes = append(codes, code)
			psr0Abs[ns] = append(psr0Abs[ns], abs)
		}
		namespacesFile += "    " + fsutil.VarExport(ns) + " => array(" + strings.Join(codes, ", ") + "),\n"
	}
	namespacesFile += ");\n"
	psr4Abs := map[string][]string{}
	for _, ns := range autoloads.psr4.keys {
		var codes []string
		for _, p := range autoloads.psr4.vals[ns] {
			code, abs := g.getPathCode(p)
			codes = append(codes, code)
			psr4Abs[ns] = append(psr4Abs[ns], abs)
		}
		psr4File += "    " + fsutil.VarExport(ns) + " => array(" + strings.Join(codes, ", ") + "),\n"
	}
	psr4File += ");\n"

	targetDirLoader := ""
	mainAutoload := root.Autoload()
	if root.TargetDir() != "" && mainAutoload != nil {
		if psr0, ok := mainAutoload.Get("psr-0"); ok && phpjson.Truthy(psr0) {
			levels := strings.Count(fsutil.NormalizePath(root.TargetDir()), "/") + 1
			var prefixes []string
			phpjson.Each(psr0, func(k string, _ phpjson.Value) { prefixes = append(prefixes, fsutil.VarExport(k)) })
			baseDirFromTarget, _ := fsutil.FindShortestPathCode(targetDir, basePath, true, false, false)
			targetDirLoader = "\n    public static function autoload($class)\n    {\n        $dir = " + baseDirFromTarget + " . '/';\n        $prefixes = array(" + strings.Join(prefixes, ", ") + ");\n        foreach ($prefixes as $prefix) {\n            if (0 !== strpos($class, $prefix)) {\n                continue;\n            }\n            $path = $dir . implode('/', array_slice(explode('\\\\', $class), " + strconv.Itoa(levels) + ")).'.php';\n            if (!$path = stream_resolve_include_path($path)) {\n                return false;\n            }\n            require $path;\n\n            return true;\n        }\n    }\n"
		}
	}

	cmg := NewGenerator(opts.Cwd)
	for _, dir := range autoloads.classmap {
		ex, err := g.buildExclusionRegexWithVendorDir(dir, autoloads.exclude)
		if err != nil {
			return nil, err
		}
		if err := cmg.ScanPaths(dir, ex, "classmap", ""); err != nil {
			return nil, err
		}
	}
	if scanPsr {
		type group struct {
			paths []string
			typ   string
		}
		toScan := map[string][]group{}
		var nsKeys []string
		for _, t := range []struct {
			m   *nsMap
			typ string
		}{{autoloads.psr4, "psr-4"}, {autoloads.psr0, "psr-0"}} {
			for _, ns := range t.m.keys {
				if _, ok := toScan[ns]; !ok {
					nsKeys = append(nsKeys, ns)
				}
				toScan[ns] = append(toScan[ns], group{t.m.vals[ns], t.typ})
			}
		}
		sort.SliceStable(nsKeys, func(i, j int) bool { return phpjson.PHPCompareKeys(nsKeys[i], nsKeys[j]) > 0 })
		for _, ns := range nsKeys {
			for _, grp := range toScan[ns] {
				for _, dir := range grp.paths {
					d := dir
					if !fsutil.IsAbsolutePath(d) {
						d = basePath + "/" + d
					}
					d = fsutil.NormalizePath(d)
					if st, err := os.Stat(d); err != nil || !st.IsDir() {
						continue
					}
					ex, err := g.buildExclusionRegexWithVendorDir(d, autoloads.exclude)
					if err != nil {
						return nil, err
					}
					if err := cmg.ScanPaths(d, ex, grp.typ, ns); err != nil {
						return nil, err
					}
				}
			}
		}
	}
	cm := cmg.ClassMap
	cm.AddClass(`Composer\InstalledVersions`, vendorPath+"/composer/InstalledVersions.php")
	ambOrder, amb := cm.AmbiguousClasses(!opts.StrictAmbiguous)
	folders := cm.AmbiguousFolders(!opts.StrictAmbiguous)
	for _, class := range ambOrder {
		paths := amb[class]
		if len(paths) > 1 {
			warn(fmt.Sprintf(`<warning>Warning: Ambiguous class resolution, "%s" was found %dx: in "%s" and "%s", the first will be used.</warning>`, class, len(paths)+1, cm.Map[class], strings.Join(paths, `", "`)))
		} else {
			warn(fmt.Sprintf(`<warning>Warning: Ambiguous class resolution, "%s" was found in both "%s" and "%s", the first will be used.</warning>`, class, cm.Map[class], strings.Join(paths, `", "`)))
		}
	}
	for _, f := range folders {
		warn(`<warning>Warning: Ambiguous path casing, "` + strings.Join(f, `", "`) + `" only differ in casing and merge into one on case-insensitive filesystems (e.g. Windows and macOS), which breaks autoloading there.</warning>`)
	}
	if len(ambOrder) > 0 || len(folders) > 0 {
		warn("<info>To resolve ambiguity in classes not under your control you can ignore them by path using <href=https://getcomposer.org/doc/04-schema.md#exclude-files-from-classmaps>exclude-from-classmap</>")
	}
	cm.ClearPsrViolationsByPath(vendorPath)
	violations := cm.PsrViolations()
	for _, v := range violations {
		warn("<warning>" + v + "</warning>")
	}

	classmapFile := "<?php\n\n// autoload_classmap.php @generated by Composer\n\n$vendorDir = " + vendorPathCode + ";\n$baseDir = " + appBaseDirCode + ";\n\nreturn array(\n"
	classAbs := map[string]string{}
	sorted := cm.SortedClasses()
	for _, class := range sorted {
		code, abs := g.getPathCode(cm.Map[class])
		classAbs[class] = abs
		classmapFile += "    " + fsutil.VarExport(class) + " => " + code + ",\n"
	}
	classmapFile += ");\n"

	suffix := opts.Suffix
	if suffix == "" {
		suffix = opts.ConfigSuffix
		if suffix == "" {
			if content, err := os.ReadFile(vendorPath + "/autoload.php"); err == nil {
				if m := regexp.MustCompile(`ComposerAutoloaderInit([^:\s]+)::`).FindSubmatch(content); m != nil {
					suffix = string(m[1])
				}
			}
		}
		if suffix == "" {
			if regexp.MustCompile(`^[a-f0-9]+$`).MatchString(opts.LockContentHash) {
				suffix = opts.LockContentHash
			} else {
				var b [16]byte
				_, _ = rand.Read(b[:])
				suffix = hex.EncodeToString(b[:])
			}
		}
	}
	result := &Result{ClassMap: cm, PsrViolations: violations, DevMode: devMode}
	if opts.DryRun {
		return result, nil
	}
	write := func(name, content string) error {
		return fsutil.FilePutContentsIfModified(name, []byte(content))
	}
	if err := write(targetDir+"/autoload_namespaces.php", namespacesFile); err != nil {
		return nil, err
	}
	if err := write(targetDir+"/autoload_psr4.php", psr4File); err != nil {
		return nil, err
	}
	if err := write(targetDir+"/autoload_classmap.php", classmapFile); err != nil {
		return nil, err
	}
	includePathsContents := g.includePathsFile(packageMap, vendorPathCode, appBaseDirCode)
	if includePathsContents != "" {
		if err := write(targetDir+"/include_paths.php", includePathsContents); err != nil {
			return nil, err
		}
	} else {
		os.Remove(targetDir + "/include_paths.php")
	}
	filesContents, filesAbs := g.includeFilesFile(autoloads.files, vendorPathCode, appBaseDirCode, warn)
	if filesContents != "" {
		if err := write(targetDir+"/autoload_files.php", filesContents); err != nil {
			return nil, err
		}
	} else {
		os.Remove(targetDir + "/autoload_files.php")
	}
	static := g.staticFile(suffix, realTarget, filesContents != "", filesAbs, autoloads, psr0Abs, psr4Abs, sorted, classAbs)
	if err := write(targetDir+"/autoload_static.php", static); err != nil {
		return nil, err
	}
	checkPlatform := opts.PlatformCheck != false && !opts.IgnoreAllPlatform
	platformCheck := ""
	if checkPlatform {
		platformCheck = g.platformCheck(packageMap, opts.PlatformCheck, devPackageNames, opts.IgnorePlatform)
		if platformCheck == "" {
			checkPlatform = false
		}
	}
	if checkPlatform {
		if err := write(targetDir+"/platform_check.php", platformCheck); err != nil {
			return nil, err
		}
	} else {
		os.Remove(targetDir + "/platform_check.php")
	}
	if err := write(vendorPath+"/autoload.php", autoloadFile(vendorPathToTargetDirCode, suffix)); err != nil {
		return nil, err
	}
	prepend := "true"
	if !opts.PrependAutoloader {
		prepend = "false"
	}
	real := autoloadRealFile(includePathsContents != "", targetDirLoader, filesContents != "", suffix, opts.UseIncludePath, prepend, checkPlatform, opts.ClassMapAuthoritative, opts.Apcu, opts.ApcuPrefix)
	if err := write(targetDir+"/autoload_real.php", real); err != nil {
		return nil, err
	}
	if err := write(targetDir+"/ClassLoader.php", string(res.ClassLoader)); err != nil {
		return nil, err
	}
	if err := write(targetDir+"/LICENSE", string(res.License)); err != nil {
		return nil, err
	}
	return result, nil
}

type gen struct {
	basePath   string
	vendorPath string
	devMode    bool
	root       *pkg.Package
	cwd        string
}

func validatePackage(p *pkg.Package) error {
	al := p.Autoload()
	if al == nil {
		return nil
	}
	psr4, ok := al.Get("psr-4")
	if !ok || !phpjson.Truthy(psr4) {
		return nil
	}
	if p.TargetDir() != "" {
		return fmt.Errorf("PSR-4 autoloading is incompatible with the target-dir property, remove the target-dir in package '%s'.", p.Name)
	}
	var err error
	phpjson.Each(psr4, func(ns string, _ phpjson.Value) {
		if err == nil && ns != "" && !strings.HasSuffix(ns, `\`) {
			err = fmt.Errorf(`psr-4 namespaces must end with a namespace separator, '%s' does not, use '%s\'.`, ns, ns)
		}
	})
	return err
}

type nsMap struct {
	keys []string
	vals map[string][]string
}

func newNSMap() *nsMap { return &nsMap{vals: map[string][]string{}} }

func (m *nsMap) add(k, v string) {
	if _, ok := m.vals[k]; !ok {
		m.keys = append(m.keys, k)
	}
	m.vals[k] = append(m.vals[k], v)
}

type filesMap struct {
	keys []string
	vals map[string]string
}

type autoloadData struct {
	psr0, psr4 *nsMap
	classmap   []string
	files      *filesMap
	exclude    []string
}

func (g *gen) parseAutoloads(packageMap []PackageEntry, filtered any) *autoloadData {
	rootEntry := packageMap[0]
	rest := packageMap[1:]
	switch f := filtered.(type) {
	case []string:
		var keep []PackageEntry
		for _, e := range rest {
			dev := false
			for _, n := range f {
				if n == e.Pkg.Name {
					dev = true
				}
			}
			if !dev {
				keep = append(keep, e)
			}
		}
		rest = keep
	case bool:
		if f {
			rest = g.filterPackageMap(rest)
		}
	}
	sortedMap := sortPackageMap(rest)
	sortedMap = append(sortedMap, rootEntry)
	reversed := make([]PackageEntry, len(sortedMap))
	for i := range sortedMap {
		reversed[i] = sortedMap[len(sortedMap)-1-i]
	}
	out := &autoloadData{psr0: newNSMap(), psr4: newNSMap(), files: &filesMap{vals: map[string]string{}}}
	g.parseType(reversed, "psr-0", out)
	g.parseType(reversed, "psr-4", out)
	g.parseType(reversed, "classmap", out)
	g.parseType(sortedMap, "files", out)
	g.parseType(sortedMap, "exclude-from-classmap", out)
	krsort := func(m *nsMap) {
		sort.SliceStable(m.keys, func(i, j int) bool { return phpjson.PHPCompareKeys(m.keys[i], m.keys[j]) > 0 })
	}
	krsort(out.psr0)
	krsort(out.psr4)
	return out
}

func (g *gen) filterPackageMap(entries []PackageEntry) []PackageEntry {
	packages := map[string]*pkg.Package{}
	replacedBy := map[string]string{}
	for _, e := range entries {
		packages[e.Pkg.Name] = e.Pkg
		for _, r := range e.Pkg.Replaces() {
			replacedBy[r.Target] = e.Pkg.Name
		}
	}
	include := map[string]bool{}
	var add func(p *pkg.Package)
	add = func(p *pkg.Package) {
		for _, l := range p.Requires() {
			t := l.Target
			if r, ok := replacedBy[t]; ok {
				t = r
			}
			if !include[t] {
				include[t] = true
				if pp, ok := packages[t]; ok {
					add(pp)
				}
			}
		}
	}
	add(g.root)
	var out []PackageEntry
	for _, e := range entries {
		for _, n := range e.Pkg.Names(true) {
			if include[n] {
				out = append(out, e)
				break
			}
		}
	}
	return out
}

// sortPackageMap is PackageSorter::sortPackages applied to the map.
func sortPackageMap(entries []PackageEntry) []PackageEntry {
	byName := map[string]PackageEntry{}
	var order []string
	for _, e := range entries {
		if _, ok := byName[e.Pkg.Name]; !ok {
			order = append(order, e.Pkg.Name)
		}
		byName[e.Pkg.Name] = e
	}
	usage := map[string][]string{}
	for _, n := range order {
		p := byName[n].Pkg
		links := p.Requires()
		if p.IsRoot {
			links = append(append(pkg.Links(nil), links...), p.DevRequires()...)
		}
		for _, l := range links {
			usage[l.Target] = append(usage[l.Target], p.Name)
		}
	}
	computing := map[string]bool{}
	computed := map[string]int{}
	var importance func(name string) int
	importance = func(name string) int {
		if w, ok := computed[name]; ok {
			return w
		}
		if computing[name] {
			return 0
		}
		computing[name] = true
		w := 0
		for _, user := range usage[name] {
			w -= 1 - importance(user)
		}
		delete(computing, name)
		computed[name] = w
		return w
	}
	type wp struct {
		name   string
		weight int
	}
	var weighted []wp
	for _, n := range order {
		weighted = append(weighted, wp{n, importance(n)})
	}
	sort.SliceStable(weighted, func(i, j int) bool {
		if weighted[i].weight != weighted[j].weight {
			return weighted[i].weight < weighted[j].weight
		}
		return semver.NatCompare(strings.ToLower(weighted[i].name), strings.ToLower(weighted[j].name)) < 0
	})
	out := make([]PackageEntry, len(weighted))
	for i, w := range weighted {
		out[i] = byName[w.name]
	}
	return out
}

// arrayMergeRecursive is PHP array_merge_recursive for decoded JSON values.
func arrayMergeRecursive(a, b phpjson.Value) phpjson.Value {
	out := phpjson.NewMap()
	n := 0
	put := func(v phpjson.Value) {
		phpjson.Each(v, func(k string, val phpjson.Value) {
			if _, isInt := phpjson.IntKey(k); isInt {
				out.Set(strconv.Itoa(n), val)
				n++
				return
			}
			if cur, ok := out.Get(k); ok {
				out.Set(k, arrayMergeRecursive(toArr(cur), toArr(val)))
				return
			}
			out.Set(k, val)
		})
	}
	put(a)
	put(b)
	return out
}

func toArr(v phpjson.Value) phpjson.Value {
	if phpjson.IsArray(v) {
		return v
	}
	if v == nil {
		return []phpjson.Value{}
	}
	return []phpjson.Value{v}
}

func toPaths(v phpjson.Value) []string {
	if !phpjson.IsArray(v) {
		if v == nil {
			return nil
		}
		s, _ := phpjson.ScalarString(v)
		return []string{s}
	}
	var out []string
	phpjson.Each(v, func(_ string, e phpjson.Value) {
		s, _ := phpjson.ScalarString(e)
		out = append(out, s)
	})
	return out
}

var reExcludeUpdir = regexp.MustCompile(`^((?:(?:\\\.){1,2}/)+)`)

func (g *gen) parseType(entries []PackageEntry, typ string, out *autoloadData) {
	for _, e := range entries {
		p := e.Pkg
		if e.InstallPath == nil {
			continue
		}
		installPath := *e.InstallPath
		var autoload phpjson.Value = phpjson.NewMap()
		if a := p.Autoload(); a != nil {
			autoload = a
		}
		if g.devMode && p == g.root {
			var dev phpjson.Value = phpjson.NewMap()
			if d := p.DevAutoload(); d != nil {
				dev = d
			}
			autoload = arrayMergeRecursive(autoload, dev)
		}
		am := phpjson.ToMap(autoload)
		if am == nil {
			continue
		}
		section, ok := am.Get(typ)
		if !ok || !phpjson.IsArray(section) {
			continue
		}
		if p.TargetDir() != "" && p != g.root {
			installPath = installPath[:len(installPath)-len("/"+p.TargetDir())]
		}
		phpjson.Each(section, func(namespace string, paths phpjson.Value) {
			if typ == "psr-4" || typ == "psr-0" {
				namespace = strings.TrimLeft(namespace, `\`)
			}
			for _, path := range toPaths(paths) {
				if (typ == "files" || typ == "classmap" || typ == "exclude-from-classmap") && p.TargetDir() != "" && !readable(installPath+"/"+path) {
					if p == g.root {
						td := strings.ReplaceAll(regexp.QuoteMeta(strings.NewReplacer("/", "<dirsep>", `\`, "<dirsep>").Replace(p.TargetDir())), "<dirsep>", `[\\/]`)
						path = strings.TrimLeft(regexp.MustCompile(`^`+td).ReplaceAllString(strings.TrimLeft(path, `\/`), ""), `\/`)
					} else {
						path = p.TargetDir() + "/" + path
					}
				}
				if typ == "exclude-from-classmap" {
					ep := regexp.MustCompile(`/+`).ReplaceAllString(pregQuote(strings.Trim(strings.ReplaceAll(path, `\`, "/"), "/")), "/")
					ep = strings.NewReplacer(`\*\*`, ".+?", `\*`, "[^/]+?").Replace(ep)
					updir := ""
					if m := reExcludeUpdir.FindStringSubmatch(ep); m != nil {
						updir = strings.ReplaceAll(m[1], `\.`, ".")
						ep = ep[len(m[0]):]
					}
					ip := installPath
					if ip == "" {
						ip = strings.ReplaceAll(g.cwd, `\`, "/")
					}
					resolved := fsutil.Realpath(ip + "/" + updir)
					if resolved == "" {
						continue
					}
					out.exclude = append(out.exclude, pregQuote(strings.ReplaceAll(resolved, `\`, "/"))+"/"+ep+"($|/)")
					continue
				}
				var relativePath string
				if installPath == "" {
					if path == "" {
						relativePath = "."
					} else {
						relativePath = path
					}
				} else {
					relativePath = installPath + "/" + path
				}
				switch typ {
				case "files":
					sum := md5.Sum([]byte(p.Name + ":" + path))
					id := hex.EncodeToString(sum[:])
					if _, ok := out.files.vals[id]; !ok {
						out.files.keys = append(out.files.keys, id)
					}
					out.files.vals[id] = relativePath
				case "classmap":
					out.classmap = append(out.classmap, relativePath)
				case "psr-0":
					out.psr0.add(namespace, relativePath)
				case "psr-4":
					out.psr4.add(namespace, relativePath)
				}
			}
		})
	}
}

func readable(p string) bool {
	f, err := os.Open(p)
	if err != nil {
		return false
	}
	f.Close()
	return true
}

// pregQuote is PHP preg_quote() without delimiter.
func pregQuote(s string) string {
	var sb strings.Builder
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch c {
		case '.', '\\', '+', '*', '?', '[', '^', ']', '$', '(', ')', '{', '}', '=', '!', '<', '>', '|', ':', '-', '#':
			sb.WriteByte('\\')
			sb.WriteByte(c)
		case 0:
			sb.WriteString(`\000`)
		default:
			sb.WriteByte(c)
		}
	}
	return sb.String()
}

// getPathCode returns the PHP code for a path and the absolute path it evaluates to.
func (g *gen) getPathCode(path string) (string, string) {
	if !fsutil.IsAbsolutePath(path) {
		path = g.basePath + "/" + path
	}
	path = fsutil.NormalizePath(path)
	baseDir := ""
	abs := ""
	if strings.HasPrefix(path+"/", g.vendorPath+"/") {
		rel := path[len(g.vendorPath):]
		baseDir = "$vendorDir . "
		abs = g.vendorPath + rel
		path = rel
	} else {
		sp, _ := fsutil.FindShortestPath(g.basePath, path, true, false)
		sp = fsutil.NormalizePath(sp)
		if !fsutil.IsAbsolutePath(sp) {
			baseDir = "$baseDir . "
			path = "/" + sp
			abs = g.basePath + path
		} else {
			path = sp
			abs = sp
		}
	}
	if regexp.MustCompile(`\.phar([\\/]|$)`).MatchString(path) {
		baseDir = "'phar://' . " + baseDir
		abs = "phar://" + abs
	}
	return baseDir + fsutil.VarExport(path), abs
}

func (g *gen) buildExclusionRegexWithVendorDir(dir string, excluded []string) (*regexp.Regexp, error) {
	ex := append([]string(nil), excluded...)
	resolved := dir
	if !fsutil.IsAbsolutePath(resolved) {
		resolved = fsutil.Realpath(g.cwd) + "/" + dir
	}
	resolved = fsutil.NormalizePath(resolved)
	if strings.HasPrefix(g.vendorPath, resolved+"/") {
		ex = append(ex, pregQuote(g.vendorPath+"/"))
	}
	return g.buildExclusionRegex(dir, ex)
}

func constantPrefix(pattern string) string {
	special := ".+*?[^]$(){}=!<>|:\\#-"
	var sb strings.Builder
	for i := 0; i < len(pattern); i++ {
		c := pattern[i]
		if c == '\\' {
			if i+1 < len(pattern) && strings.IndexByte(".+*?[^]$(){}=!<>|:#-", pattern[i+1]) >= 0 {
				sb.WriteByte(c)
				sb.WriteByte(pattern[i+1])
				i++
				continue
			}
			break
		}
		if strings.IndexByte(special, c) >= 0 {
			break
		}
		sb.WriteByte(c)
	}
	return sb.String()
}

func (g *gen) buildExclusionRegex(dir string, excluded []string) (*regexp.Regexp, error) {
	if len(excluded) == 0 {
		return nil, nil
	}
	if _, err := os.Stat(dir); err == nil {
		dirMatch := pregQuote(strings.ReplaceAll(fsutil.Realpath(dir), `\`, "/"))
		absDir := dir
		if !fsutil.IsAbsolutePath(dir) {
			absDir = fsutil.Realpath(g.cwd) + "/" + dir
		}
		dirMatchNormalized := pregQuote(strings.ReplaceAll(fsutil.NormalizePath(absDir), `\`, "/"))
		isSymlink := dirMatch != dirMatchNormalized
		var keep []string
		for _, pattern := range excluded {
			prefix := constantPrefix(pattern)
			unrelated := !strings.HasPrefix(prefix, dirMatch) && !strings.HasPrefix(dirMatch, prefix) &&
				(!isSymlink || (!strings.HasPrefix(prefix, dirMatchNormalized) && !strings.HasPrefix(dirMatchNormalized, prefix)))
			if !unrelated {
				keep = append(keep, pattern)
			}
		}
		excluded = keep
	}
	if len(excluded) == 0 {
		return nil, nil
	}
	re, err := regexp.Compile("(" + strings.Join(excluded, "|") + ")")
	if err != nil {
		return nil, fmt.Errorf("invalid exclude-from-classmap pattern: %v", err)
	}
	return re, nil
}

func (g *gen) includePathsFile(packageMap []PackageEntry, vendorPathCode, appBaseDirCode string) string {
	var paths []string
	for _, e := range packageMap {
		if e.InstallPath == nil {
			continue
		}
		ip := *e.InstallPath
		if td := e.Pkg.TargetDir(); td != "" {
			ip = ip[:len(ip)-len("/"+td)]
		}
		for _, inc := range e.Pkg.IncludePaths() {
			inc = strings.Trim(inc, "/")
			if ip == "" {
				paths = append(paths, inc)
			} else {
				paths = append(paths, ip+"/"+inc)
			}
		}
	}
	if len(paths) == 0 {
		return ""
	}
	code := ""
	for _, p := range paths {
		c, _ := g.getPathCode(p)
		code += "    " + c + ",\n"
	}
	return "<?php\n\n// include_paths.php @generated by Composer\n\n$vendorDir = " + vendorPathCode + ";\n$baseDir = " + appBaseDirCode + ";\n\nreturn array(\n" + code + ");\n"
}

func (g *gen) includeFilesFile(files *filesMap, vendorPathCode, appBaseDirCode string, warn func(string)) (string, map[string]string) {
	codes := map[string]string{}
	abs := map[string]string{}
	seen := map[string]bool{}
	var dups []string
	for _, id := range files.keys {
		c, a := g.getPathCode(files.vals[id])
		codes[id] = c
		abs[id] = a
		if seen[c] {
			found := false
			for _, d := range dups {
				if d == c {
					found = true
				}
			}
			if !found {
				dups = append(dups, c)
			}
		}
		seen[c] = true
	}
	if len(dups) > 0 {
		warn(`<warning>The following "files" autoload rules are included multiple times, this may cause issues and should be resolved:</warning>`)
		for _, d := range dups {
			warn("<warning> - " + d + "</warning>")
		}
	}
	code := ""
	for _, id := range files.keys {
		code += "    " + fsutil.VarExport(id) + " => " + codes[id] + ",\n"
	}
	if code == "" {
		return "", nil
	}
	return "<?php\n\n// autoload_files.php @generated by Composer\n\n$vendorDir = " + vendorPathCode + ";\n$baseDir = " + appBaseDirCode + ";\n\nreturn array(\n" + code + ");\n", abs
}

func autoloadFile(vendorPathToTargetDirCode, suffix string) string {
	last := vendorPathToTargetDirCode[len(vendorPathToTargetDirCode)-1]
	if last == '\'' || last == '"' {
		vendorPathToTargetDirCode = vendorPathToTargetDirCode[:len(vendorPathToTargetDirCode)-1] + "/autoload_real.php" + string(last)
	} else {
		vendorPathToTargetDirCode += " . '/autoload_real.php'"
	}
	return `<?php

// autoload.php @generated by Composer

if (PHP_VERSION_ID < 50600) {
    if (!headers_sent()) {
        header('HTTP/1.1 500 Internal Server Error');
    }
    $err = 'Composer 2.3.0 dropped support for autoloading on PHP <5.6 and you are running '.PHP_VERSION.', please upgrade PHP or use Composer 2.2 LTS via "composer self-update --2.2". Aborting.'.PHP_EOL;
    if (!ini_get('display_errors')) {
        if (PHP_SAPI === 'cli' || PHP_SAPI === 'phpdbg') {
            fwrite(STDERR, $err);
        } elseif (!headers_sent()) {
            echo $err;
        }
    }
    throw new RuntimeException($err);
}

require_once ` + vendorPathToTargetDirCode + `;

return ComposerAutoloaderInit` + suffix + `::getLoader();
`
}

func autoloadRealFile(useIncludePath bool, targetDirLoader string, useIncludeFiles bool, suffix string, useGlobalIncludePath bool, prepend string, checkPlatform, authoritative, apcu bool, apcuPrefix string) string {
	f := `<?php

// autoload_real.php @generated by Composer

class ComposerAutoloaderInit` + suffix + `
{
    private static $loader;

    public static function loadClassLoader($class)
    {
        if ('Composer\Autoload\ClassLoader' === $class) {
            require __DIR__ . '/ClassLoader.php';
        }
    }

    /**
     * @return \Composer\Autoload\ClassLoader
     */
    public static function getLoader()
    {
        if (null !== self::$loader) {
            return self::$loader;
        }

`
	if checkPlatform {
		f += "        require __DIR__ . '/platform_check.php';\n\n"
	}
	f += "        spl_autoload_register(array('ComposerAutoloaderInit" + suffix + "', 'loadClassLoader'), true, " + prepend + ");\n" +
		"        self::$loader = $loader = new \\Composer\\Autoload\\ClassLoader(\\dirname(__DIR__));\n" +
		"        spl_autoload_unregister(array('ComposerAutoloaderInit" + suffix + "', 'loadClassLoader'));\n\n"
	if useIncludePath {
		f += "        $includePaths = require __DIR__ . '/include_paths.php';\n        $includePaths[] = get_include_path();\n        set_include_path(implode(PATH_SEPARATOR, $includePaths));\n\n"
	}
	f += "        require __DIR__ . '/autoload_static.php';\n        call_user_func(\\Composer\\Autoload\\ComposerStaticInit" + suffix + "::getInitializer($loader));\n\n"
	if authoritative {
		f += "        $loader->setClassMapAuthoritative(true);\n"
	}
	if apcu {
		prefix := apcuPrefix
		if prefix == "" {
			var b [10]byte
			_, _ = rand.Read(b[:])
			prefix = hex.EncodeToString(b[:])
		}
		f += "        $loader->setApcuPrefix(" + fsutil.VarExport(prefix) + ");\n"
	}
	if useGlobalIncludePath {
		f += "        $loader->setUseIncludePath(true);\n"
	}
	if targetDirLoader != "" {
		f += "        spl_autoload_register(array('ComposerAutoloaderInit" + suffix + "', 'autoload'), true, true);\n\n"
	}
	f += "        $loader->register(" + prepend + ");\n\n"
	if useIncludeFiles {
		f += "        $filesToLoad = \\Composer\\Autoload\\ComposerStaticInit" + suffix + "::$files;\n" +
			"        $requireFile = \\Closure::bind(static function ($fileIdentifier, $file) {\n" +
			"            if (empty($GLOBALS['__composer_autoload_files'][$fileIdentifier])) {\n" +
			"                $GLOBALS['__composer_autoload_files'][$fileIdentifier] = true;\n\n" +
			"                require $file;\n" +
			"            }\n" +
			"        }, null, null);\n" +
			"        foreach ($filesToLoad as $fileIdentifier => $file) {\n" +
			"            $requireFile($fileIdentifier, $file);\n" +
			"        }\n\n"
	}
	f += "        return $loader;\n    }\n"
	f += targetDirLoader
	return f + "}\n"
}
